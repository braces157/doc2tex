/** Refresh the license inventory shipped with the compiled frontend. Run after npm ci. */
import { execFileSync } from 'node:child_process'
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const frontend = join(root, 'frontend')
// npm returns the actual installed production tree, including hoisted dependencies.
const command = process.platform === 'win32' ? 'npm.cmd' : 'npm'
const paths = execFileSync(command, ['ls', '--omit=dev', '--all', '--parseable'], {
  cwd: frontend, encoding: 'utf8', shell: process.platform === 'win32',
}).trim().split(/\r?\n/).filter(path => path !== frontend)
const notices = []
for (const path of [...new Set(paths)].sort()) {
  const pkg = JSON.parse(readFileSync(join(path, 'package.json'), 'utf8'))
  const files = readdirSync(path).filter(name => /^(licen[sc]e|copying|notice)(\.|$)/i.test(name))
  const label = `${pkg.name}@${pkg.version} (${pkg.license ?? 'see upstream'})`
  const contents = files.map(name => `--- ${name} ---\n${readFileSync(join(path, name), 'utf8').trim()}`)
  notices.push(`${label}\n${'='.repeat(label.length)}\n${contents.join('\n\n') || 'See the package repository for license terms.'}`)
}
writeFileSync(join(root, 'LICENSES/frontend-dependencies.txt'),
  'Frontend production dependency notices\nGenerated by node scripts/collect-licenses.mjs after npm ci.\n\n' + notices.join('\n\n') + '\n')
console.log(`Collected notices for ${notices.length} production packages.`)
